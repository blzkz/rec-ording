/// A piece of a recording on the video track.
#[derive(Debug, Clone, Copy, PartialEq, Serialize, Deserialize)]
pub struct Clip {
    pub id: u64,
    pub media: u64,
    pub source_in: f32,
    pub source_out: f32,
    /// Playback speed (2 = twice as fast).
    #[serde(default = "one")]
    pub speed: f32,
    /// A still of the frame at `source_in`, held for this many seconds.
    #[serde(default)]
    pub freeze: Option<f32>,
}

fn one() -> f32 {
    1.0
}

impl Clip {
    pub fn new(id: u64, media: u64, source_in: f32, source_out: f32) -> Self {
        Clip { id, media, source_in, source_out, speed: 1.0, freeze: None }
    }

    /// Seconds it lasts on the timeline.
    pub fn duration(&self) -> f32 {
        match self.freeze {
            Some(secs) => secs.max(0.0),
            None => (self.source_out - self.source_in).max(0.0) / self.speed.max(0.01),
        }
    }
}

/// How a keyframe is reached from the previous one.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
pub enum Ease {
    /// Fast start, soft landing, like a damped spring.
    Spring,
    /// Eases in and out.
    Smooth,
    Linear,
    /// Keeps the previous value and jumps at the keyframe.
    Hold,
}

impl Ease {
    pub const ALL: [Ease; 4] = [Ease::Spring, Ease::Smooth, Ease::Linear, Ease::Hold];

    pub fn label(self) -> &'static str {
        match self {
            Ease::Spring => "Muelle",
            Ease::Smooth => "Suave",
            Ease::Linear => "Lineal",
            Ease::Hold => "Corte",
        }
    }
}

/// Camera at a keyframe. `t` is relative to the clip start; angles are added to the style's
/// device angle (0 = unchanged); `zoom` 1 and focus (0.5, 0.5) is the resting camera.
#[derive(Debug, Clone, Copy, PartialEq, Serialize, Deserialize)]
pub struct CamKey {
    pub t: f32,
    pub zoom: f32,
    pub x: f32,
    pub y: f32,
    pub tilt: f32,
    pub turn: f32,
    pub roll: f32,
    pub ease: Ease,
}

impl CamKey {
    pub fn rest(t: f32, ease: Ease) -> Self {
        Self { t, zoom: 1.0, x: 0.5, y: 0.5, tilt: 0.0, turn: 0.0, roll: 0.0, ease }
    }
}

