export interface ExportSettings {
  presetId: ExportPresetId;
  width: number;
  height: number;
  fps: 30 | 60;
  codec: VideoCodec;
  crf: number; // 14-35
  transparentBackground: boolean;
  includeAudio: boolean;
  burnSubtitles: boolean;
  motionBlurSamples: number; // 1 (off), 4, 8, 16
  outputPath: string;
}

export interface TelemetryPointerEvent {
  id: string;
  timestampMs: number;
  source: 'desktop' | 'android';
  type: 'move' | 'click' | 'down' | 'up' | 'touch_tap' | 'touch_swipe';
  /** Normalized 0..1 coordinates relative to the captured source */
  x: number;
  y: number;
  endX?: number;
  endY?: number;
  durationMs?: number;
  button?: 'left' | 'right' | 'middle' | 'finger';
}

export interface TelemetryKeyEvent {
  id: string;
  timestampMs: number;
  keyCombo: string; // e.g., "Ctrl + Shift + R", "Back", "Volume Up"
  durationMs: number;
}

export interface Keyframe<T = number> {
  id: string;
  timeSec: number; // Project timeline time in seconds
  value: T;
  easing: 'linear' | 'easeInOutCubic' | 'spring' | 'easeOutExpo';
}

export interface DirectorCameraKeyframe {
  id: string;
  timeSec: number;
  durationSec: number;
  /** Target focus point in normalized screen coords (0..1, 0..1) */
  focusX: number;
  focusY: number;
  /** Zoom level: 1.0 = full view, 2.2 = zoomed in */
  zoom: number;
  /** 3D device rotation in degrees */
  rotXDeg: number;
  rotYDeg: number;
  rotZDeg: number;
  easing: 'spring' | 'easeInOutCubic' | 'linear';
  label?: string;
  autoGenerated?: boolean;
}

export interface FreezeFrameSegment {
  id: string;
  sourceTimeSec: number; // Which frame in the clip to freeze
  timelineStartSec: number;
  durationSec: number;
}

export interface PrivacyMask {
  id: string;
  label: string;
  trackClipId?: string;
  startSec: number;
  endSec: number;
  /** Normalized 0..1 coordinates over target video or canvas */
  x: number;
  y: number;
  width: number;
  height: number;
  mode: 'blur' | 'pixelate' | 'solid';
  intensity: number; // blur radius or pixel size (5..50)
  color?: string;
  keyframes?: Array<{
    timeSec: number;
    x: number;
    y: number;
    width: number;
    height: number;
  }>;
}

export type TitleAnimationPreset =
  | 'pop-elastic'
  | 'slide-up-blur'
  | 'typewriter'
  | 'glass-badge'
  | 'neon-glow'
  | 'minimal-fade';

export interface TimelineClip {
  id: string;
  trackId: string;
  name: string;
  type: 'video' | 'audio' | 'text';
  /** Path or URL to media file (for video/audio) */
  mediaPath?: string;
  /** Role of video clip for 3D scene mapping */
  sourceRole?: 'android-main' | 'pc-screen' | 'webcam' | 'overlay';
  /** Start time on project timeline (seconds) */
  startSec: number;
  /** Duration on timeline (seconds) */
  durationSec: number;
  /** Trim in-point inside source media (seconds) */
  trimInSec: number;
  /** Trim out-point inside source media (seconds) */
  trimOutSec: number;
  /** Playback speed multiplier (0.25 .. 4.0) */
  speed: number;
  /** Audio volume (0.0 .. 2.0) */
  volume: number;
  muted: boolean;
  fadeInSec: number;
  fadeOutSec: number;
  /** Freeze frame insertions */
  freezeFrames: FreezeFrameSegment[];
  /** Visual transform keyframes */
  opacityKeyframes: Keyframe<number>[];
  scaleKeyframes: Keyframe<number>[];
  /** Text clip specific fields */
  text?: string;
  subtitleText?: string;
  titlePreset?: TitleAnimationPreset;
  fontSize?: number;
  textColor?: string;
  bgColor?: string;
  posX?: number; // 0..1
  posY?: number; // 0..1
}

export interface TimelineTrack {
  id: string;
  name: string;
  kind: 'video' | 'audio' | 'text';
  index: number; // 1..4 for video/audio, 1..5 for text
  muted: boolean;
  solo: boolean;
  locked: boolean;
  volume: number; // 0..2 for audio/video tracks
  clips: TimelineClip[];
}

